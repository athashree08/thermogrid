"""
ThermoGrid — Data Quality & Validation Engine
Audits dataset integrity, null values, range constraints, and uniqueness checks.
"""

import json
from datetime import datetime, timezone
import streamlit as st
import pandas as pd
from dashboard.utils.data_loader import (
    load_data_quality_report,
    load_weather_aggregated,
    load_weather_geospatial
)
from src.validation.data_quality import validate_weather_data


def render_data_quality():
    st.markdown('<div class="tg-brand-subtitle">Integrity & Quality Assurance</div>', unsafe_allow_html=True)
    st.title("Data Quality & Governance")

    # Dynamic load of report
    report = load_data_quality_report()
    df_agg = load_weather_aggregated()

    # Live Audit Trigger
    col_hdr1, col_hdr2 = st.columns([3, 1.2])
    with col_hdr1:
        st.caption("Verification results generated by `src/validation/data_quality.py` against aggregated weather records.")
    with col_hdr2:
        if st.button("🔄 Execute Live Quality Audit", use_container_width=True):
            if not df_agg.empty:
                live_report = validate_weather_data(df_agg)
                st.session_state["live_audit_result"] = live_report
                st.session_state["live_audit_time"] = datetime.now(timezone.utc).strftime("%H:%M:%S UTC")
                st.success("Live validation audit completed successfully!")
            else:
                st.warning("Cannot execute audit: aggregated dataset is empty.")

    # Check if live report in session state
    if "live_audit_result" in st.session_state:
        report = st.session_state["live_audit_result"]
        audit_time = st.session_state.get("live_audit_time", "Recent")
        st.info(f"Displaying results from Live Audit run at {audit_time}.")

    passed = report.get("passed", False)
    total_records = report.get("total_records", 0)

    # Top Status Banner
    if passed:
        st.markdown(
            f"""
            <div style="background: rgba(16, 185, 129, 0.12); border: 1px solid rgba(16, 185, 129, 0.4); border-left: 5px solid #10B981; border-radius: 8px; padding: 16px 20px; margin-bottom: 24px;">
                <div style="display: flex; justify-content: space-between; align-items: center;">
                    <div>
                        <span style="font-size: 1.1rem; font-weight: 700; color: #34D399;">✓ DATA QUALITY AUDIT PASSED</span>
                        <div style="color: #94A3B8; font-size: 0.85rem; margin-top: 4px;">
                            All integrity constraints satisfied across {total_records} aggregated records. Zero anomalies detected.
                        </div>
                    </div>
                    <span class="tg-badge-success">100% HEALTHY</span>
                </div>
            </div>
            """,
            unsafe_allow_html=True
        )
    else:
        st.markdown(
            f"""
            <div style="background: rgba(239, 68, 68, 0.15); border: 1px solid rgba(239, 68, 68, 0.4); border-left: 5px solid #EF4444; border-radius: 8px; padding: 16px 20px; margin-bottom: 24px;">
                <span style="font-size: 1.1rem; font-weight: 700; color: #F87171;">✕ DATA QUALITY AUDIT FAILED</span>
                <div style="color: #FCA5A5; font-size: 0.85rem; margin-top: 4px;">
                    One or more validation constraints failed. Review check items below.
                </div>
            </div>
            """,
            unsafe_allow_html=True
        )

    # Summary KPI Cards
    k1, k2, k3, k4 = st.columns(4)
    with k1:
        st.markdown(
            f"""
            <div class="tg-metric-box">
                <div class="tg-metric-label">Audited Records</div>
                <div class="tg-metric-value">{total_records}</div>
                <div class="tg-metric-delta">Full Partition Batch</div>
            </div>
            """,
            unsafe_allow_html=True
        )

    with k2:
        dup_count = report.get("duplicate_records", 0)
        dup_color = "#34D399" if dup_count == 0 else "#EF4444"
        st.markdown(
            f"""
            <div class="tg-metric-box">
                <div class="tg-metric-label">Duplicate Composite Keys</div>
                <div class="tg-metric-value" style="color: {dup_color};">{dup_count}</div>
                <div class="tg-metric-delta">(geohash, timestamp)</div>
            </div>
            """,
            unsafe_allow_html=True
        )

    with k3:
        null_counts = report.get("null_counts", {})
        total_nulls = sum(null_counts.values()) if null_counts else 0
        null_color = "#34D399" if total_nulls == 0 else "#EF4444"
        st.markdown(
            f"""
            <div class="tg-metric-box">
                <div class="tg-metric-label">Null / Missing Values</div>
                <div class="tg-metric-value" style="color: {null_color};">{total_nulls}</div>
                <div class="tg-metric-delta">Across {len(null_counts)} Columns</div>
            </div>
            """,
            unsafe_allow_html=True
        )

    with k4:
        missing_cols = report.get("missing_columns", [])
        schema_status = "Compliant" if not missing_cols else f"Missing {len(missing_cols)}"
        schema_color = "#34D399" if not missing_cols else "#EF4444"
        st.markdown(
            f"""
            <div class="tg-metric-box">
                <div class="tg-metric-label">Schema Compliance</div>
                <div class="tg-metric-value" style="color: {schema_color}; font-size: 1.3rem; padding-top: 5px;">{schema_status}</div>
                <div class="tg-metric-delta">9 Required Columns</div>
            </div>
            """,
            unsafe_allow_html=True
        )

    st.write("")
    st.markdown("### Detailed Quality Checks Specification")

    # Checks Table Data
    checks_data = [
        {
            "Check ID": "CHK-01",
            "Verification Rule": "Schema Completeness",
            "Constraint / Threshold": "All 9 mandatory fields present",
            "Observed Anomalies": len(report.get("missing_columns", [])),
            "Status": "PASSED" if not report.get("missing_columns", []) else "FAILED"
        },
        {
            "Check ID": "CHK-02",
            "Verification Rule": "Composite Key Uniqueness",
            "Constraint / Threshold": "Unique (geohash, timestamp)",
            "Observed Anomalies": report.get("duplicate_records", 0),
            "Status": "PASSED" if report.get("duplicate_records", 0) == 0 else "FAILED"
        },
        {
            "Check ID": "CHK-03",
            "Verification Rule": "Temperature Plausibility",
            "Constraint / Threshold": "Range: -90°C to +65°C",
            "Observed Anomalies": report.get("invalid_temperature", 0),
            "Status": "PASSED" if report.get("invalid_temperature", 0) == 0 else "FAILED"
        },
        {
            "Check ID": "CHK-04",
            "Verification Rule": "Relative Humidity Bounds",
            "Constraint / Threshold": "Range: 0% to 100%",
            "Observed Anomalies": report.get("invalid_humidity", 0),
            "Status": "PASSED" if report.get("invalid_humidity", 0) == 0 else "FAILED"
        },
        {
            "Check ID": "CHK-05",
            "Verification Rule": "Precipitation Non-Negativity",
            "Constraint / Threshold": "Value >= 0.0 mm",
            "Observed Anomalies": report.get("negative_precipitation", 0),
            "Status": "PASSED" if report.get("negative_precipitation", 0) == 0 else "FAILED"
        },
        {
            "Check ID": "CHK-06",
            "Verification Rule": "Wind Speed Non-Negativity",
            "Constraint / Threshold": "Value >= 0.0 km/h",
            "Observed Anomalies": report.get("negative_wind_speed", 0),
            "Status": "PASSED" if report.get("negative_wind_speed", 0) == 0 else "FAILED"
        },
        {
            "Check ID": "CHK-07",
            "Verification Rule": "Geodetic Coordinates Bounds",
            "Constraint / Threshold": "Lat [-90, 90], Lon [-180, 180]",
            "Observed Anomalies": report.get("invalid_coordinates", 0),
            "Status": "PASSED" if report.get("invalid_coordinates", 0) == 0 else "FAILED"
        },
        {
            "Check ID": "CHK-08",
            "Verification Rule": "Completeness / No Nulls",
            "Constraint / Threshold": "Zero nulls in any column",
            "Observed Anomalies": sum(report.get("null_counts", {}).values()),
            "Status": "PASSED" if sum(report.get("null_counts", {}).values()) == 0 else "FAILED"
        }
    ]

    checks_df = pd.DataFrame(checks_data)
    st.dataframe(checks_df, use_container_width=True, hide_index=True)

    # Column Null Counts Table
    st.markdown("### Column-Level Null Distribution Breakdown")
    null_counts_dict = report.get("null_counts", {})
    if null_counts_dict:
        null_df = pd.DataFrame(list(null_counts_dict.items()), columns=["Column Name", "Missing (Null) Count"])
        null_df["Missing Percentage"] = "0.0%"
        null_df["Integrity Status"] = "✓ Clean"

        col_tbl, col_raw = st.columns([1.5, 1.2])
        with col_tbl:
            st.dataframe(null_df, use_container_width=True, hide_index=True)
        with col_raw:
            st.markdown("#### Raw Quality JSON Payload")
            st.json(report)


if __name__ == "__main__":
    render_data_quality()

